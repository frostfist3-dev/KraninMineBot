import os
import secrets
import time
from typing import Dict, Set

from fastapi import FastAPI, Header, HTTPException, Request
from pydantic import BaseModel, Field
from telegram import Update
from telegram.ext import Application, CommandHandler, ContextTypes

BOT_TOKEN = os.environ["BOT_TOKEN"]
BRIDGE_SECRET = os.environ["BRIDGE_SECRET"]
PUBLIC_URL = os.environ["PUBLIC_URL"].rstrip("/")
WEBHOOK_SECRET = os.environ.get("WEBHOOK_SECRET", secrets.token_urlsafe(24))

app = FastAPI(title="Telegram Script Notifier")

# Starter implementation for testing only: bindings are kept in memory and
# will be lost when Render restarts/redeploys the service. Add Postgres for
# persistent production use.
pending_codes: Dict[str, float] = {}
subscribers: Set[int] = set()

tg_app = Application.builder().token(BOT_TOKEN).build()


async def start_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if not update.effective_chat or not update.effective_user:
        return
    code = context.args[0] if context.args else None
    if code:
        expiry = pending_codes.pop(code, None)
        if expiry and expiry > time.time():
            subscribers.add(update.effective_chat.id)
            await update.message.reply_text(
                "✅ Уведомления подключены! Теперь сюда будут приходить события скрипта."
            )
            return
        await update.message.reply_text(
            "Код привязки недействителен или истёк. Создай новый код в скрипте и попробуй снова."
        )
        return
    await update.message.reply_text(
        "Привет! Чтобы подключить уведомления, нажми кнопку подключения в Lua-скрипте, "
        "затем перейди по ссылке и нажми Start."
    )


async def help_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "Команды:\n/start — запуск и привязка\n/status — проверить подключение\n/stop — отключить уведомления"
    )


async def status_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    chat_id = update.effective_chat.id
    await update.message.reply_text(
        "Уведомления подключены." if chat_id in subscribers else
        "Уведомления ещё не подключены. Открой скрипт и используй кнопку подключения."
    )


async def stop_cmd(update: Update, context: ContextTypes.DEFAULT_TYPE):
    chat_id = update.effective_chat.id
    subscribers.discard(chat_id)
    await update.message.reply_text("Уведомления отключены для этого чата.")


tg_app.add_handler(CommandHandler("start", start_cmd))
tg_app.add_handler(CommandHandler("help", help_cmd))
tg_app.add_handler(CommandHandler("status", status_cmd))
tg_app.add_handler(CommandHandler("stop", stop_cmd))


class LinkRequest(BaseModel):
    # Use a random, one-time code generated by your Lua app/server.
    code: str = Field(min_length=16, max_length=128)


class EventRequest(BaseModel):
    event: str = Field(min_length=1, max_length=40)
    message: str = Field(default="", max_length=700)


@app.on_event("startup")
async def startup():
    await tg_app.initialize()
    await tg_app.start()
    await tg_app.bot.set_webhook(
        url=f"{PUBLIC_URL}/telegram/webhook",
        secret_token=WEBHOOK_SECRET,
        allowed_updates=["message"],
    )


@app.on_event("shutdown")
async def shutdown():
    await tg_app.bot.delete_webhook()
    await tg_app.stop()
    await tg_app.shutdown()


@app.get("/")
async def root():
    return {"ok": True, "service": "telegram-script-notifier"}


@app.post("/telegram/webhook")
async def telegram_webhook(request: Request, x_telegram_bot_api_secret_token: str = Header(default="")):
    if not secrets.compare_digest(x_telegram_bot_api_secret_token, WEBHOOK_SECRET):
        raise HTTPException(status_code=403, detail="Forbidden")
    payload = await request.json()
    update = Update.de_json(payload, tg_app.bot)
    await tg_app.process_update(update)
    return {"ok": True}


@app.post("/api/link")
async def create_link(req: LinkRequest, x_bridge_secret: str = Header(default="")):
    if not secrets.compare_digest(x_bridge_secret, BRIDGE_SECRET):
        raise HTTPException(status_code=403, detail="Forbidden")
    pending_codes[req.code] = time.time() + 600
    return {"ok": True, "start_url": f"https://t.me/{os.environ['BOT_USERNAME']}?start={req.code}", "expires_in": 600}


@app.post("/api/event")
async def send_event(req: EventRequest, x_bridge_secret: str = Header(default="")):
    if not secrets.compare_digest(x_bridge_secret, BRIDGE_SECRET):
        raise HTTPException(status_code=403, detail="Forbidden")
    allowed = {"START", "STOP", "CRASH", "LICENSE", "STATUS"}
    if req.event not in allowed:
        raise HTTPException(status_code=400, detail="Unsupported event")
    labels = {
        "START": "🟢 СТАРТ",
        "STOP": "⏹️ СТОП",
        "CRASH": "🔴 ВОЗМОЖНЫЙ ВЫЛЕТ / ПОТЕРЯ СВЯЗИ",
        "LICENSE": "🔑 ПРОБЛЕМА С ЛИЦЕНЗИЕЙ",
        "STATUS": "📊 СТАТУС",
    }
    text = labels[req.event]
    if req.message:
        text += "\n" + req.message
    failed = 0
    for chat_id in list(subscribers):
        try:
            await tg_app.bot.send_message(chat_id=chat_id, text=text)
        except Exception:
            failed += 1
    return {"ok": True, "sent_to": len(subscribers) - failed, "failed": failed}
